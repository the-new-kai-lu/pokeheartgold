#!/usr/bin/env python3
"""Read-only inventory checks for an explicitly generated opening source tree.

This is not a composer, installer, compiled-bank validator or runtime test.
It deliberately does not weaken the default native script SHA inventory.
"""

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import stat
import subprocess


def safe_relative(name):
    path = PurePosixPath(name)
    if (not name or "\\" in name or path.is_absolute()
            or any(part in ("", ".", "..") for part in name.split("/"))
            or str(path) != name):
        raise ValueError(f"Unsafe inventory path: {name!r}")
    return path


def regular_bytes(root, name):
    relative = safe_relative(name)
    current = Path(root)
    if current.is_symlink() or not current.is_dir():
        raise ValueError("Root must be a real directory")
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise ValueError(f"Symlink forbidden in audited source path: {name}")
    if not stat.S_ISREG(current.stat().st_mode):
        raise ValueError(f"Not a regular source file: {name}")
    return current.read_bytes()


def digest(data):
    return hashlib.sha256(data).hexdigest()


