def native_names(root):
    tracked = subprocess.check_output(
        ["git", "-C", str(root), "ls-tree", "-rz", "--name-only", "HEAD"]
    ).decode().rstrip("\0").split("\0")
    return sorted(set(EPISODE_ADDITIONS).union(
        name for name in tracked
        if name.startswith(("asm/", "src/", "include/", "lib/", "files/", "sub/",
                            "heartgold.us/", "soulsilver.us/", "tools/"))
        or name in {
            "Makefile", "CMakeLists.txt", "binutils.mk", "common.mk", "config.mk",
            "filesystem.mk", "graphics_files_rules.mk", "platform.mk",
            "charmap.txt", "global.inc", "main.lsf", "rom.rsf", "scr_seq.sha1",
            "expansion/baseline.json",
        }))


def native_inputs(root, tree):
    """Complete native input inventory; NOT a compiled-bank acceptance policy."""
    return {name: digest(regular_bytes(tree, name)) for name in native_names(root)}


EPISODE_SCRIPT_BANKS = frozenset({
    "scr_seq_0843_T20R0101.bin",
    "scr_seq_0965_hoenn_reward.bin",
    "scr_seq_0966_route101_opening_hdr.bin",
})


def verify_compiled_inventory(directory, baseline_manifest, episode_sha1):
    """Opt-in bank audit; caller supplies independently approved episode hashes.

    No compilation is performed. The default build_native_field_scripts policy
    and scr_seq.sha1 are untouched. Every non-episode bank retains its original
    SHA1 requirement; all three changed/appended banks require explicit pins.
    """
    if set(episode_sha1) != EPISODE_SCRIPT_BANKS:
        raise ValueError("Exactly the three episode bank pins are required")
    if any(len(value) != 40 or any(c not in "0123456789abcdef" for c in value)
           for value in episode_sha1.values()):
        raise ValueError("Invalid episode SHA1")
    baseline = Path(baseline_manifest).read_bytes()
    if digest(baseline) != "1d71988ee54402fcf52adcb822f01ce6c3cc75f88b3e478150664f0d96ee52be":
        raise ValueError("Default compiled-bank manifest differs from pinned baseline")
    expected = {}
    for line in baseline.decode().splitlines():
        expected_hash, name = line.split()
        name = Path(name.lstrip("*")).name
        if name in expected:
            raise ValueError("Duplicate baseline script bank")
        expected[name] = expected_hash
    if len(expected) != 966 or "scr_seq_0966_route101_opening_hdr.bin" in expected:
        raise ValueError("Expected unchanged default 966-bank inventory")
    expected.update(episode_sha1)
    directory = Path(directory)
    if {p.name for p in directory.glob("*.bin")} != set(expected):
        raise ValueError("Compiled episode bank inventory differs")
    for name, expected_hash in expected.items():
        if hashlib.sha1(regular_bytes(directory, name)).hexdigest() != expected_hash:
            raise ValueError(f"Compiled script mismatch: {name}")
    return {"banks": len(expected), "unchanged_default_banks": 964,
            "explicit_episode_banks": sorted(episode_sha1)}


def compare(root, generated):
    """Compare every committed regular source file, not an incremental subset.

    Generated extras are inventoried separately. A symlink is recorded as such,
    never followed; deleted tracked files and changed symlinks remain explicit.
    Git metadata and Python caches are not native inputs.
    """
    root, generated = Path(root), Path(generated)
    if root.resolve() == generated.resolve():
        raise ValueError("Generated tree must be distinct from the checkout")
    revision = subprocess.check_output(
        ["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    records = subprocess.check_output(
        ["git", "-C", str(root), "ls-tree", "-rz", "--full-tree", "HEAD"])
    tracked, changes = set(), {}
    for record in records.split(b"\0"):
        if not record:
            continue
        metadata, encoded_name = record.split(b"\t", 1)
        mode, kind, oid = metadata.split()
        name = encoded_name.decode("utf-8")
        safe_relative(name)
        tracked.add(name)
        target = generated / name
        before = subprocess.check_output(
            ["git", "-C", str(root), "cat-file", "blob", oid.decode()])
        if mode == b"120000":
            after = target.readlink().as_posix().encode() if target.is_symlink() else None
        elif kind == b"blob":
            after = regular_bytes(generated, name) if target.exists() or target.is_symlink() else None
        else:
            raise ValueError(f"Unsupported tracked entry: {name}")
        if before != after:
            changes[name] = {
                "before": digest(before),
                "after": None if after is None else digest(after),
                "kind": "symlink" if mode == b"120000" else "regular",
            }
    extras = {}
    for path in sorted(generated.rglob("*")):
        name = path.relative_to(generated).as_posix()
        if any(part in (".git", "__pycache__") for part in path.relative_to(generated).parts):
            continue
        if name in tracked:
            continue
        if name.startswith("tools/mwccarm/"):
            # These owner-local compiler/SDK/license files are not source
            # provenance and must never be read into a distributable inventory.
            extras[name] = {"kind": "excluded-user-local-proprietary-toolchain"}
            continue
        if path.is_symlink():
            # Inventory is not installation approval: record, never follow.
            extras[name] = {"kind": "derived-symlink" if name in DERIVED_RULES
                            else "unclassified-symlink",
                            "target": path.readlink().as_posix()}
            if name in DERIVED_RULES:
                extras[name]["rule"] = DERIVED_RULES[name]
            continue
        if path.is_dir():
            continue
        extras[name] = ({"kind": "derived", "rule": DERIVED_RULES[name]}
                        if name in DERIVED_RULES else digest(regular_bytes(generated, name)))
    return {
        "status": "read-only-generated-source-inventory-not-runtime-proof",
        "base_commit": revision,
        "tracked_entries": len(tracked),
        "changed_tracked": changes,
        "generated_extras": extras,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--generated", required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps(compare(args.root, args.generated), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()